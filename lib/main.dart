class HomePage extends StatelessWidget {
  const HomePage({super.key});
  @override
  Widget build(BuildContext context) => Directionality(
        textDirection: TextDirection.rtl,
        child: Scaffold(
          appBar: AppBar(title: const Text('إحتراف التداول من الصفر الى الاحترف')),
          body: ListView.builder(
            padding: const EdgeInsets.all(16),
            itemCount: lessons.length,
            itemBuilder: (context, index) {
              final lesson = lessons[index];
              return Card(
                margin: const EdgeInsets.only(bottom: 12),
                child: ListTile(
                  contentPadding: const EdgeInsets.all(16),
                  leading: CircleAvatar(child: Text('${index + 1}')),
                  title: Text(lesson.title, style: const TextStyle(fontWeight: FontWeight.bold)),
                  subtitle: Padding(
                    padding: const EdgeInsets.only(top: 8),
                    child: Text(lesson.summary),
                  ),
                  trailing: const Icon(Icons.arrow_back_ios_new),
                  onTap: () => Navigator.push(
                    context,
                    MaterialPageRoute(builder: (_) => LessonPage(lesson: lesson)),
                  ),
                ),
              );
            },
          ),
          bottomNavigationBar: const Padding(
            padding: EdgeInsets.fromLTRB(16, 4, 16, 12),
            child: Text(
              'محتوى تعليمي مبني على المحاضرات. لا توجد ضمانات للربح ولا توصية شخصية بالشراء أو البيع.',
              textAlign: TextAlign.center,
              style: TextStyle(fontSize: 12, color: Colors.white60),
            ),
          ),
        ),
      );
}

