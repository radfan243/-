          appBar: AppBar(title: Text(lesson.title)),
          body: ListView(
            padding: const EdgeInsets.all(18),
            children: [
              Text(lesson.summary, style: Theme.of(context).textTheme.titleMedium),
              const SizedBox(height: 18),
              for (final point in lesson.points)
                Card(
                  margin: const EdgeInsets.only(bottom: 10),
                  child: Padding(
                    padding: const EdgeInsets.all(14),
                    child: Row(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        const Icon(Icons.check_circle_outline, color: Colors.amber),
                        const SizedBox(width: 10),
                        Expanded(child: Text(point, style: const TextStyle(height: 1.45))),
                      ],
                    ),
                  ),
                ),
            ],
          ),
        ),
      );
}
